// Defines the package namespace grouping enumeration types for entity attributes
package com.spring.entity.enums;

// Declares the enum categorizing technical incident requests submitted to CampusDESK
public enum TicketCategory {
    // Identifies issues related to physical equipment such as computers and peripherals
    HARDWARE,
    // Identifies issues related to operating systems, tools, and campus desktop applications
    SOFTWARE,
    // Identifies issues regarding internet access, Wi-Fi connectivity, and routing
    NETWORK,
    // Identifies issues regarding user credentials, authentication accounts, and access permissions
    ACCESS,
    // Identifies generic or unclassified incidents requiring help desk attention
    OTHER
// Closes the TicketCategory enum definition
}
